import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const tenantIdIndex = process.argv.indexOf('--tenant-id');
const tenantId = tenantIdIndex >= 0 ? process.argv[tenantIdIndex + 1] : '456';

if (!tenantId || tenantId.startsWith('--')) {
  throw new Error('Provide a tenant ID with --tenant-id <id>.');
}

class MemoryLocalStorage {
  private values = new Map<string, string>();

  getItem(key: string): string | null {
    return this.values.get(key) ?? null;
  }

  setItem(key: string, value: string): void {
    this.values.set(key, String(value));
  }

  removeItem(key: string): void {
    this.values.delete(key);
  }

  clear(): void {
    this.values.clear();
  }

  key(index: number): string | null {
    return [...this.values.keys()][index] ?? null;
  }

  get length(): number {
    return this.values.size;
  }
}

Object.defineProperty(globalThis, 'localStorage', {
  configurable: true,
  value: new MemoryLocalStorage(),
});

const [{ Storage }, { OperationsStorage }] = await Promise.all([
  import('../src/utils/storage.ts'),
  import('../src/utils/operationsStorage.ts'),
]);

function sanitize(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(sanitize);
  if (!value || typeof value !== 'object') return value;

  return Object.fromEntries(
    Object.entries(value)
      .filter(([key]) => !key.toLowerCase().includes('password'))
      .map(([key, item]) => [
        key,
        (key === 'tenantId' || key === 'schoolId') && typeof item === 'string'
          ? tenantId
          : sanitize(item),
      ])
  );
}

function sqlLiteral(value: unknown): string {
  return `'${JSON.stringify(value).replace(/'/g, "''")}'::jsonb`;
}

type SeedRow = {
  tenantId: string;
  collection: string;
  recordId: string;
  payload: unknown;
};

const seedCollections: Record<string, unknown> = {
  ...Storage.getInitialSeedCollections(),
  ...OperationsStorage.getInitialSeedCollections(),
};
const excludedCollections = new Set([
  'edusmart_grade_passwords_v1',
  'edusmart_role_permissions_v1',
  'edusmart_users_v1',
]);
const rows: SeedRow[] = [];
const counts = new Map<string, number>();

for (const [collection, value] of Object.entries(seedCollections)) {
  if (excludedCollections.has(collection)) continue;
  if (!Array.isArray(value)) continue;

  const records = value.flatMap((payload, index) => {
    if (!payload || typeof payload !== 'object') return [];
    const id = 'id' in payload && payload.id !== null && payload.id !== undefined
      ? String(payload.id)
      : `idx:${index}`;
    return [{
      tenantId,
      collection,
      recordId: id,
      payload: sanitize(payload),
    }];
  });
  if (!records.length) continue;
  counts.set(collection, records.length);
  rows.push(...records);
}

if (rows.length === 0) {
  throw new Error('No seedable record collections were found.');
}

const valuesPerInsert = 250;
const insertStatements: string[] = [];
for (let offset = 0; offset < rows.length; offset += valuesPerInsert) {
  const batch = rows.slice(offset, offset + valuesPerInsert);
  const values = batch.map(row => `(${[
    `'${row.tenantId.replace(/'/g, "''")}'`,
    `'${row.collection.replace(/'/g, "''")}'`,
    `'${row.recordId.replace(/'/g, "''")}'`,
    sqlLiteral(row.payload),
    'false',
  ].join(', ')})`);
  insertStatements.push(
    `insert into public.app_records (tenant_id, collection, record_id, payload, deleted)\nvalues\n  ${values.join(',\n  ')}\non conflict (tenant_id, collection, record_id) do nothing;`
  );
}

const directory = resolve('supabase', 'sql');
const seedFileName = `app_records_seed_tenant_${tenantId.replace(/[^a-zA-Z0-9_-]/g, '_')}.sql`;
await mkdir(directory, { recursive: true });
await writeFile(
  resolve(directory, seedFileName),
  [
    '-- Generated by npm run generate:supabase-sql -- --tenant-id 456.',
    '-- Source: persisted record collections from src/data and storage registries.',
    '-- Review the sample/demo records before using this file for production.',
    `-- Target tenant: ${tenantId}. Existing rows are preserved via ON CONFLICT DO NOTHING.`,
    'begin;',
    ...insertStatements,
    'commit;',
    '',
  ].join('\n\n'),
  'utf8'
);

await writeFile(
  resolve(directory, 'seed_manifest.txt'),
  [
    `Tenant ID: ${tenantId}`,
    `Total records: ${rows.length}`,
    'Records by collection:',
    ...[...counts.entries()].sort(([a], [b]) => a.localeCompare(b)).map(
      ([collection, count]) => `  ${collection}: ${count}`
    ),
    '',
    'Excluded: user credentials, grade passwords, role permissions, platform customization,',
    'starter documentation, platform tenant registry, and non-persisted reference/configuration constants.',
    '',
  ].join('\n'),
  'utf8'
);

console.info(`Generated ${rows.length} records across ${counts.size} collections for tenant ${tenantId}.`);
console.info(`SQL: ${resolve(directory, seedFileName)}`);
